/**
 * rc_cmd.h  ——  串口文本命令遥控（手柄到货前的过渡方案）
 * =====================================================================
 *  在串口助手里用"文本模式"发送下面这些命令，就能直接开车：
 *
 *    T50      油门 50%（范围 -100 ~ +100，正数前进）
 *    T-30     油门 -30%（倒车）
 *    S-20     方向 -20%（负数左转，正数右转）
 *    B        刹车：油门立刻归零
 *    Z        全部归零
 *    E        急停（锁定，之后 T/S 无效）
 *    R        解除急停
 *    ?        打印命令帮助
 *
 *  ★ 每条命令必须以回车（\r 或 \n）结尾，串口助手记得勾"发送新行"。
 *  ★ 安全设计：3 秒内没有收到新命令，主循环会自动停车。
 */
#ifndef RC_CMD_H
#define RC_CMD_H

#include "rc_protocol.h"

/** 绑定到哪个 rc_input_t 上，并清空状态 */
void rc_cmd_init(rc_input_t *in);

/** 每收到一个串口字节调用一次 */
void rc_cmd_feed(uint8_t byte);

#endif /* RC_CMD_H */
